export function getCountryCn(code: string): string {
  const clean = (code || "").trim().toUpperCase();
  return COUNTRY_CN_MAP[clean] || clean;
}

export function getLocationCn(location: string): string {
  const clean = (location || "").trim();
  return clean.toLowerCase() === "tashkent" ? "塔什干" : clean;
}

export function getPlayerCn(fullName: string): string {
  if (!fullName) return "";
  const clean = fullName.trim();
  if (clean.includes("/")) {
    return clean
      .split("/")
      .map((part) => getPlayerCn(part))
      .join(" / ");
  }

  if (PLAYER_CN_MAP[clean]) return PLAYER_CN_MAP[clean];
  const lower = clean.toLowerCase();
  for (const [key, value] of Object.entries(PLAYER_CN_MAP)) {
    if (key.toLowerCase() === lower) return value;
  }
  return clean;
}

export function getEventKey(matchKey: string): string {
  const match = Object.keys(EVENT_CN).find((key) => matchKey.startsWith(key));
  return match || matchKey.split(".").slice(0, 2).join(".") + "-----------";
}

export function getEventNameCn(eventKey: string): string {
  return EVENT_CN[eventKey] || eventKey;
}

export function getEventNameEn(eventKey: string): string {
  return EVENT_EN[eventKey] || eventKey;
}

export function getRoundNameCn(description: string, eventKey: string): string {
  const english = getEventNameEn(eventKey);
  let suffix = (description || "").replace(english, "").replace(/^\s*-\s*/, "").trim();
  if (!suffix) return "赛程待定";

  suffix = suffix
    .replace(/Preliminary Round\s+(\d+)/gi, "预赛第$1轮")
    .replace(/Group\s+(\d+)\s*-\s*Match\s+(\d+)/gi, "第$1组 · 第$2场")
    .replace(/Group\s+(\d+)/gi, "第$1组")
    .replace(/Round of\s+(\d+)/gi, "$1强")
    .replace(/Quarterfinals?/gi, "1/4决赛")
    .replace(/Semifinals?/gi, "半决赛")
    .replace(/Finals?/gi, "决赛")
    .replace(/Pos\.\s*(\d+)-(\d+)/gi, "$1-$2名排位赛")
    .replace(/Match\s+(\d+)/gi, "第$1场");

  return suffix;
}

export function getStatusLabel(status: number): string {
  if (status === 2) return "比赛进行中";
  if (status === 1) return "已完赛";
  return "即将开始";
}
